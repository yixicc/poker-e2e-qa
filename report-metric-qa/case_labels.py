def pos_title(code: str, name: str, calc_type: str) -> str:
    if code in POS_TITLE:
        return POS_TITLE[code]
    if calc_type == "T2" or name.endswith("率"):
        return "分子分母按清单手算"
    if calc_type == "T0":
        return "有值且与录像一致"
    if calc_type == "T3":
        return "取值来自结算或换算"
    if calc_type == "T4":
        return "各类标签各有正例"
    if calc_type == "T7":
        return "白名单内条件齐全"
    return "只计应计入项"


def neg_title(code: str) -> str:
    return NEG_TITLE.get(code, "与场面不符的手")


def neg_given(code: str, name: str, is_rate: bool) -> str:
    suffix = f"「{name}」仍=a/b" if is_rate else f"「{name}」仍=n"
    if code in NEG_GIVEN:
        return f"{NEG_GIVEN[code]}，{suffix}"
    tail = NEG_TITLE.get(code, "该手不应算入")
    return f"{tail}，{suffix}"
